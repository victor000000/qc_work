    def _make_indicator(self, t, cfg):
        nm = cfg['i']
        p = cfg.get('p', 14) or 14
        MAS = MovingAverageType.SIMPLE
        MAE = MovingAverageType.EXPONENTIAL
        MAW = MovingAverageType.WILDERS
        R = Resolution.DAILY
        if nm in self._IND_CANDLE:
            candle_fn = self._ind_candle_disp.get(nm)
            if candle_fn is not None:
                return candle_fn(t)
            return self.ibs(t)
        if nm in self._IND_SIMPLE:
            return self._ind_simple_disp[nm](t, p, R)
        if nm in self._IND_MATYPE_SIMPLE:
            return self._ind_matype_disp[nm](t, p, MAS, R)
        entry = self._IND_CUSTOM.get(nm) or self._IND_CUSTOM['ibs']
        method_name, arg_fn = entry
        return self._ind_custom_disp[method_name](t, *arg_fn(p, MAS, MAE, MAW), R)
    def _get_val(self, t) -> 'float | None':
        v = self.ind.get(t)
        if v is None or not v.is_ready: return None
        extractor = self._val_extract.get(t)
        if extractor is not None:
            return extractor(v)
        return v.current.value
    def on_data(self, data):
        self.pending_entries = []
        self.pending_exits = []
        for _, cfg in self.sc.items():
            self._process_etf(cfg, data)
    def _process_etf(self, cfg, data):
        t = cfg['t']
        sym = self.syms[t]
        if not data.contains_key(sym): return
        bar = data[sym]
        if bar is None: return
        price = float(bar.close)
        self._update_state(t, cfg, price)
        val = self._get_val(t)
        if val is None: return
        tf = self.trend_filter[t]
        tf_v = float(tf.current.value) if tf.is_ready else None
        if self.portfolio[sym].invested:
            if self._should_exit(t, cfg, sym, price, val, tf_v):
                self.pending_exits.append(sym)
            return
        wt = self._entry_weight(t, cfg, price, val, tf_v)
        if wt is not None:
            self.pending_entries.append((sym, wt))
    def _update_state(self, t, cfg, price):
        prev = self.prev_close.get(t)
        self.prev_close[t] = price
        if prev is not None:
            if price < prev:
                self.cdd_cnt[t] = self.cdd_cnt.get(t, 0) + 1
                self.cup_cnt[t] = 0
            elif price > prev:
                self.cup_cnt[t] = self.cup_cnt.get(t, 0) + 1
                self.cdd_cnt[t] = 0
            else:
                self.cdd_cnt[t] = 0
                self.cup_cnt[t] = 0
        prev_peak = self.eq_peak.get(t, price)
        self.eq_peak[t] = price if price > prev_peak else prev_peak
        mom_p = int(cfg.get('mom_p', 0) or 0)
        if mom_p > 0:
            mbuf = self.aux_mom_win.setdefault(t, [])
            mbuf.append(price)
            if len(mbuf) > mom_p + 1: mbuf.pop(0)
        vol_p = int(cfg.get('vol_p', 0) or 0)
        if vol_p > 0:
            vbuf = self.aux_vol_win.setdefault(t, [])
            vbuf.append(price)
            if len(vbuf) > vol_p + 1: vbuf.pop(0)
    def _should_exit(self, t, cfg, sym, price, val, tf_v) -> bool:
        pnl = float(self.portfolio[sym].unrealized_profit_percent)
        # _DEF guarantees sl/tp/xf/x present
        sl = cfg['sl']
        tp = cfg['tp']
        sl_bear = cfg.get('sl_bear', 0)
        if sl_bear and tf_v is not None and price < tf_v:
            sl = sl_bear
        atr_sl = cfg.get('atr_sl', 0)
        if atr_sl and t in self.aux_atr and self.aux_atr[t].is_ready and price > 0:
            atr_frac = float(self.aux_atr[t].current.value) / price
            if atr_frac > 0: sl = atr_sl * atr_frac
        if pnl <= -sl or pnl >= tp: return True
        if self._is_ma[t] or self._is_band[t]:
            return price > val * cfg['xf']
        if self._is_candle[t]:
            pat_x = cfg.get('pat_x', -50)
            return val is not None and val < pat_x
        x = cfg['x']
        return x != 0 and val > x
    def _entry_weight(self, t, cfg, price, val, tf_v) -> 'float | None':
        # _DEF guarantees cf/sf present
        cf = cfg['cf']
        if tf_v is not None and cf > 0 and price < tf_v * cf: return None
        sf = cfg['sf']
        tf_t = cfg.get('tf_t', 1.0)
        if not ((sf == 0) or (tf_v is None) or (price > tf_v * tf_t)): return None
        mm = cfg.get('month_mask', 0)
        if mm and not (mm & (1 << (self.time.month - 1))): return None
        rg = cfg.get('rsi_gate', 0)
        if rg and t in self.aux_rsi and self.aux_rsi[t].is_ready:
            if float(self.aux_rsi[t].current.value) > rg: return None
        adx_min = cfg.get('adx_min', 0)
        if adx_min and t in self.aux_adx and self.aux_adx[t].is_ready:
            if float(self.aux_adx[t].current.value) < adx_min: return None
        bbw_max = cfg.get('bb_width_max', 0)
        if bbw_max and t in self.aux_bbw and self.aux_bbw[t].is_ready:
            bb_ind = self.aux_bbw[t]
            upper = float(bb_ind.upper_band.current.value)
            lower = float(bb_ind.lower_band.current.value)
            mid = float(bb_ind.middle_band.current.value)
            if mid > 0:
                width = (upper - lower) / mid
                if width > bbw_max: return None
        if not self._mom_ok(t, cfg): return None
        if not self._vol_ok(t, cfg): return None
        wt = cfg['wt']
        dd_hc = cfg.get('dd_haircut', 0)
        if dd_hc and price > 0:
            peak = self.eq_peak.get(t, price)
            if peak > 0 and (peak - price) / peak > dd_hc: wt *= 0.5
        cdd_min = cfg.get('cdd_min', 0)
        cdd_boost = cfg.get('cdd_boost', 0)
        if cdd_min and cdd_boost and self.cdd_cnt.get(t, 0) >= cdd_min:
            wt *= cdd_boost
        cup_min = cfg.get('cup_min', 0)
        cup_boost = cfg.get('cup_boost', 0)
        if cup_min and cup_boost and self.cup_cnt.get(t, 0) >= cup_min:
            wt *= cup_boost
        vpt = cfg.get('vol_parity_target', 0)
        if vpt:
            own_vol = self._own_vol(t, int(cfg.get('vol_p', 0) or 0))
            if own_vol and own_vol > 0:
                wt *= max(0.5, min(2.0, vpt / own_vol))
        e = cfg['e']
        conv_depth = cfg.get('conv_depth', 0)
        e_deep = cfg.get('e_deep', 0)
        conv_deep_mult = cfg.get('conv_deep_mult', 0)
        if self._is_ma[t]:
            return min(wt, WT_CAP) if price < val * cfg['ef'] else None
        if self._is_band[t]:
            return min(wt, WT_CAP) if price < val else None
        if self._is_candle[t]:
            pat_e = cfg.get('pat_e', 50)
            return min(wt, WT_CAP) if val is not None and val > pat_e else None
        if e != 0 and val < e:
            if conv_depth and e > 0:
                depth = max(0.0, (e - val) / e)
                wt *= (1.0 + conv_depth * depth)
            if e_deep and conv_deep_mult and val < e_deep:
                wt *= conv_deep_mult
            return min(wt, WT_CAP)
        return None
    def _mom_ok(self, t, cfg) -> bool:
        mom_p = int(cfg.get('mom_p', 0) or 0)
        if mom_p <= 0: return True
        buf = self.aux_mom_win.get(t, [])
        if len(buf) < mom_p + 1 or buf[-mom_p - 1] <= 0: return True
        mom_ret = (buf[-1] - buf[-mom_p - 1]) / buf[-mom_p - 1]
        mom_min = cfg.get('mom_min', 0)
        return not (mom_min and mom_ret < mom_min)
    def _own_vol(self, t, vol_p: int):
        if vol_p <= 0: return None
        buf = self.aux_vol_win.get(t, [])
        if len(buf) < vol_p + 1: return None
        rets = [(buf[i] / buf[i-1] - 1.0) for i in range(1, len(buf)) if buf[i-1] > 0]
        if not rets: return None
        m = sum(rets) / len(rets)
        var = sum((r - m) ** 2 for r in rets) / len(rets)
        return math.sqrt(var)
    def _vol_ok(self, t, cfg) -> bool:
        vol_max = cfg.get('vol_max', 0)
        if not vol_max: return True
        v = self._own_vol(t, int(cfg.get('vol_p', 0) or 0))
        return v is None or v <= vol_max
    def execute_pending_orders(self):
        exited = set()
        for sym in list(self.pending_exits):
            if self.portfolio[sym].invested:
                self.liquidate(sym)
                exited.add(sym)
        self.pending_exits = []
        tv = self.portfolio.total_portfolio_value
        if tv <= 0:
            self.pending_entries = []
            return
        target_syms = {s for s, _ in self.pending_entries} | exited
        existing_w = sum(abs(k.value.holdings_value) / tv for k in self.portfolio
                                                  if k.value.invested and k.value.symbol not in target_syms)
        new_total = sum(w for _, w in self.pending_entries)
        budget = GROSS_CAP - existing_w
        if budget <= 0:
            self.pending_entries = []
            return
        if new_total > budget and new_total > 0:
            self.pending_entries = [(s, w * budget / new_total) for s, w in self.pending_entries]
        for sym, w in self.pending_entries:
            if w > 0.005: self.set_holdings(sym, w)
        self.pending_entries = []
